int32_t np_gen4_ntc_c1024(uint16_t code)
{
 const uint32_t clipped=code>65527u?65527u:code;
 uint64_t resistance=(uint64_t)clipped*100000u/(65535u-clipped);
 if(resistance>INT32_MAX)resistance=INT32_MAX;
 unsigned low=0,high=168;
 while(low<high){
  const unsigned middle=low+(high-low)/2;
  if(ntc[middle].ohm>resistance)low=middle+1;else high=middle;
 }
 if(!low)return ntc[0].c1024;
 if(low==168)return ntc[167].c1024;
 const Point left=ntc[low-1],right=ntc[low];
 const int64_t numerator=(int64_t)(right.c1024-left.c1024)*((int64_t)resistance-left.ohm);
 return left.c1024+(int32_t)(numerator/((int64_t)right.ohm-left.ohm));
}
int32_t np_gen4_ntc_centi(uint16_t code)
{return (int32_t)((int64_t)np_gen4_ntc_c1024(code)*100/1024);}
